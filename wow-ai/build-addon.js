'use strict';
const fs=require('fs'),path=require('path');
const addon=path.join(__dirname,'addon','WoWAI');
// Embed in the existing loaded file as well, so /reload works with a cached TOC.
// Research.lua's guard makes the standalone manifest entry harmless.
const core=fs.readFileSync(path.join(addon,'WoWAI.core.lua'),'utf8');
const research=fs.readFileSync(path.join(addon,'Research.lua'),'utf8');
const settings=fs.readFileSync(path.join(addon,'Settings.lua'),'utf8');
const theme=fs.readFileSync(path.join(addon,'Theme.lua'),'utf8');
const promptUI=fs.readFileSync(path.join(addon,'Prompts.lua'),'utf8');
const pack=path.join(__dirname,'..','docs','prompt-power-pack');
const index=fs.readFileSync(path.join(pack,'README.md'),'utf8');
const categories=JSON.parse(fs.readFileSync(path.join(pack,'categories.json'),'utf8'));
const categoryById=new Map();
for(const c of categories)for(const id of c.ids){if(categoryById.has(id))throw Error('Duplicate prompt category');categoryById.set(id,c.name);}
const luaText=s=>'[====['+s+']====]';
const prompts=[...index.matchAll(/\| \[([^\]]+)\]\((\d{2}-[^)]+\.txt)\) \| ([^\n]+?) \|/g)].sort((a,b)=>a[2].localeCompare(b[2])).map(([,title,file,summary])=>{
 const text=fs.readFileSync(path.join(pack,file),'utf8');
 if(text.includes(']====]'))throw Error('Prompt contains reserved Lua delimiter');
 const category=categoryById.get(Number(file.slice(0,2)));if(!category)throw Error('Uncategorized prompt '+file);
 return `{title=${luaText(title)},category=${luaText(category)},summary=${luaText(summary)},text=${luaText(text)}}`;
});
if(prompts.length!==28)throw Error('Expected all 28 prompt-library entries');
const promptData='WoWAI.PromptCategories = {'+categories.map(c=>luaText(c.name)).join(',')+'}\nWoWAI.PromptLibrary = {\n'+prompts.join(',\n')+'\n}\n';
const embed=text=>text.split('\n').map(line=>line.trim()?'  '+line:'').join('\n');
fs.writeFileSync(path.join(addon,'WoWAI.lua'),core+'\n\n-- Goblin Eye research UI (generated by build-addon.js)\ndo\n'+embed(research)+'\nend\n\n-- Per-chat model/settings UI\ndo\n'+embed(settings)+'\nend\n\n-- Goblin Eye grimoire theme\ndo\n'+embed(theme)+'\nend\n');
console.log('Built reload-compatible WoWAI.lua.');
fs.appendFileSync(path.join(addon,'WoWAI.lua'),'\n-- Bundled prompt library; no bridge or provider needed to browse\ndo\n'+embed(promptData+promptUI)+'\nend\n');
